#!/usr/bin/env python3
"""The Mission Editor's own F10 map icon list, read from a DCS install as text.

    python3 -I scripts/gen-me-icons.py "<DCS install>" data/me-icons.json

Source: <install>/MissionEditor/data/NewMap/images/draw/icons.lua — the list the editor's
icon picker is built from, so it is the editor's own set of drawing icons rather than a
guess at which image files exist. Facts only: the icon's file name and the editor's own
hint (its label), plus the source file's sha256 and the installed DCS build, because this
file is install-specific and cannot be regenerated without one.

Nothing is executed: the file is scanned for `{file = '<name>', hint = _('<label>')}`.
An entry without both fields is skipped rather than half-read, and a label is never
invented for a file (and no file for a label).
"""
import hashlib
import json
import pathlib
import re
import sys

ENTRY = re.compile(r"\{\s*file\s*=\s*'([^']+\.png)'\s*,\s*hint\s*=\s*_\('([^']+)'\)\s*\}")

install = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])

source = install / "MissionEditor" / "data" / "NewMap" / "images" / "draw" / "icons.lua"
raw = source.read_bytes()
text = raw.decode("utf-8", errors="replace")
# Strip line comments so the commented-out example entry at the top is not read.
text = re.sub(r"--[^\n]*", "", text)

icons = {}
order = []
for file_name, hint in ENTRY.findall(text):
    label = hint.strip()
    if not label or label in icons:
        continue
    icons[label] = file_name
    order.append(label)

if len(icons) < 10:
    sys.exit(f"only {len(icons)} icons parsed from {source}; refusing to write a partial catalogue")

version = None
cfg = install / "autoupdate.cfg"
if cfg.exists():
    try:
        version = json.loads(cfg.read_text(encoding="utf-8")).get("version")
    except ValueError:
        version = None

data = {
    "_source": "Generated by scripts/gen-me-icons.py from the Mission Editor's own icon list "
               "(MissionEditor/data/NewMap/images/draw/icons.lua) in a DCS install. Labels and file names only.",
    "_sha256": {"MissionEditor/data/NewMap/images/draw/icons.lua": hashlib.sha256(raw).hexdigest()},
    "_dcsVersion": version,
    "count": len(icons),
    # Editor order: the picker groups them (ground, air defence, air, naval, misc).
    "order": order,
    "icons": icons,
}
out.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"{out}: {len(icons)} icons from DCS {version or 'unknown build'}")
